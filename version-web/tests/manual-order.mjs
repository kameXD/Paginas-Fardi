import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import JSZip from 'jszip';
import { readFile } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage({ acceptDownloads: true });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', d => d.accept());
  await page.goto('http://localhost:5173');
  const photos = await page.evaluate(() => Array.from({length:105}, (_, i) => {
    const c = document.createElement('canvas'); c.width = c.height = 24;
    const ctx = c.getContext('2d'); ctx.fillStyle = `rgb(${i},80,150)`; ctx.fillRect(0,0,24,24);
    return c.toDataURL().split(',')[1];
  }));
  await page.locator('#files').setInputFiles(photos.map((png, i) => ({name: `foto-${i + 1}.png`, mimeType: 'image/png', buffer: Buffer.from(png, 'base64')})));
  await page.waitForFunction(() => document.querySelectorAll('.card').length === 105);
  const names = () => page.locator('.filename').allTextContents();
  const initial = await names();
  const card = name => page.locator('.card').filter({has: page.getByText(name, {exact:true})});
  const first = card('foto-1.png');
  await first.locator('input[aria-label^="Número de"]').fill('777');
  await first.locator('input[aria-label^="Número de"]').dispatchEvent('change');
  await first.locator('input[type=checkbox]').check();
  await page.locator('#confirm').click();
  await first.locator('.destination').fill('35');
  const beforeMoveScroll = await page.evaluate(() => scrollY);
  await first.locator('.destination').press('Enter');
  assert.ok(Math.abs(await page.evaluate(() => scrollY) - beforeMoveScroll) < 3);
  assert.equal((await names())[34], 'foto-1.png');
  assert.equal(await first.locator('input[aria-label^="Número de"]').inputValue(), '777');
  assert.equal(await first.locator('input[type=checkbox]').isChecked(), true);
  assert.equal(await page.locator('#word').isDisabled(), true);
  assert.equal(await first.locator('.position').textContent(), 'Posición 35 de 105');
  await page.locator('#undoMove').click();
  assert.deepEqual(await names(), initial);
  assert.equal(await page.locator('#undoMove').isDisabled(), true);
  await first.locator('.destination').fill('106');
  await first.getByRole('button', {name:'Mover', exact:true}).click();
  assert.deepEqual(await names(), initial);
  // Real mouse fallback drag, visible destination, no scroll jump at release.
  await page.locator('#viewMode').selectOption('list');
  await first.locator('.drag-handle').scrollIntoViewIfNeeded();
  let from = await first.locator('.drag-handle').boundingBox();
  let to = await card('foto-2.png').boundingBox();
  await page.mouse.move(from.x + 20, from.y + 20);
  await page.mouse.down();
  await page.mouse.move(to.x + to.width / 2, to.y + to.height * .8, {steps:20});
  await page.waitForTimeout(200);
  assert.equal(await page.locator('.drop-target').count(), 1);
  const scroll = await page.evaluate(() => scrollY);
  await page.mouse.up();
  assert.equal((await names())[1], 'foto-1.png');
  assert.ok(Math.abs(await page.evaluate(() => scrollY) - scroll) < 3);
  // Export the actual manually confirmed order, including all 105 photos.
  await page.locator('#confirm').click();
  let download = page.waitForEvent('download');
  await page.locator('#zip').click();
  let zip = await JSZip.loadAsync(await readFile(await (await download).path()));
  assert.equal(Object.keys(zip.files).length, 105);
  assert.equal(Object.keys(zip.files)[1], '777.png');
  const expectedOrder = await names();
  for (const [index, entry] of Object.keys(zip.files).entries()) {
    const photoIndex = Number(expectedOrder[index].match(/\d+/)[0]) - 1;
    assert.deepEqual(await zip.file(entry).async('nodebuffer'), Buffer.from(photos[photoIndex], 'base64'));
  }
  download = page.waitForEvent('download');
  await page.locator('#word').click();
  zip = await JSZip.loadAsync(await readFile(await (await download).path()));
  const xml = await zip.file('word/document.xml').async('string');
  assert.equal((xml.match(/<w:drawing>/g) || []).length, 105);
  assert.deepEqual([...xml.matchAll(/descr="(foto-\d+\.png)"/g)].map(m => m[1]), expectedOrder);
  // Mobile touch drag through Chromium's native touch input, grid layout.
  await page.setViewportSize({width:390,height:844});
  await page.locator('#viewMode').selectOption('grid');
  await card('foto-2.png').scrollIntoViewIfNeeded();
  from = await card('foto-2.png').locator('.drag-handle').boundingBox();
  to = await first.boundingBox();
  const cdp = await page.context().newCDPSession(page);
  const touch = (type,x,y) => cdp.send('Input.dispatchTouchEvent', {type, touchPoints:type === 'touchEnd' ? [] : [{x,y}]});
  await touch('touchStart', from.x+20, from.y+20);
  for(let i=1;i<=15;i++) await touch('touchMove', from.x+20+(to.x+to.width*.7-from.x-20)*i/15, from.y+20+(to.y+80-from.y-20)*i/15);
  await page.waitForTimeout(200);
  assert.equal(await page.locator('.drop-target').count(), 1);
  await touch('touchEnd');
  assert.equal((await names())[0], 'foto-1.png');
  assert.equal(await page.locator('#word').isDisabled(), true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('#undoMove').click();
  assert.equal((await names())[0], 'foto-2.png');
  await page.locator('#sort').click();
  assert.equal((await names())[0], 'foto-1.png');
  await page.locator('#undoMove').click();
  assert.equal((await names())[0], 'foto-2.png');
  await first.getByRole('button', {name:'↑ foto-1.png', exact:true}).click();
  assert.equal((await names())[0], 'foto-1.png');
  await page.locator('#undoMove').click();
  assert.equal((await names())[0], 'foto-2.png');
  await first.getByRole('button', {name:'Eliminar foto-1.png', exact:true}).click();
  assert.equal(await page.locator('#undoMove').isDisabled(), true);
  assert.equal((await names()).length, 104);
  assert.deepEqual(errors, []);
  console.log('PASS: 105 fotografías, destino exacto, límites, datos conservados, deshacer, arrastre de ratón/táctil, desplazamiento, lista/cuadrícula y exportaciones confirmadas.');
} finally { await browser.close(); }
